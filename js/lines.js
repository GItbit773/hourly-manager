export function say(tone, key, vars = {}) {
  const set = LINES[tone] || LINES.micro;
  let v = set[key] ?? LINES.micro[key];
  if (Array.isArray(v)) v = v[Math.floor(Math.random() * v.length)];
  return String(v).replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}
